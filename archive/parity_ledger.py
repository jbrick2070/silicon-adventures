"""Write archive/PARITY.md: where every resource on the two 1986 disks lives in this edition.

    python archive/parity_ledger.py

The numbers are computed from the disks' catalogs and the game's own tables, so a
resource that loses its place in play shows up here and fails game/tests/parity.test.js.
"""
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load_js(path, name):
    text = (ROOT / path).read_text(encoding='utf8')
    start = text.index('=') + 1
    return json.loads(text[start:text.rindex(';')] if text.rstrip().endswith(';') else text[start:])


def main():
    es = json.loads((ROOT / 'archive/es/catalog.json').read_text(encoding='utf8'))
    dc = json.loads((ROOT / 'archive/dc/catalog.json').read_text(encoding='utf8'))
    designs = json.loads((ROOT / 'archive/es/designs.json').read_text(encoding='utf8'))
    chronicle = load_js('archive/es/chronicle.js', 'ES_CHRONICLE')
    graphics = load_js('art/castle-index.js', 'CastleGraphics')
    plan_text = (ROOT / 'game/castle-plan.js').read_text(encoding='utf8')
    shell = (ROOT / 'game/enchanted-castle.js').read_text(encoding='utf8')
    folio = (ROOT / 'game/folio.js').read_text(encoding='utf8')
    kinds = Counter(line['k'] for line in chronicle['lines'])
    es_types = Counter(r['type'] for r in es['resources'])
    dc_types = Counter((r['file'].split(':')[-1], r['type']) for r in dc['resources'])
    reels = sorted(f"{g['fork'][-1]}{g['id']}" for g in graphics if g['type'] == 'PPCT')
    screens = sorted(f"{g['fork'][-1]}{g['id']}" for g in graphics if g['type'] == 'PSCR')
    block = plan_text[plan_text.index('const REELS'):plan_text.index('const SCREENS')]
    roles = {}
    for role, ids in re.findall(r"(\w+): \[((?:'[AB]\d+'(?:, )?)+)\]", block):
        for item in re.findall(r"'([AB]\d+)'", ids):
            roles[item] = role
    sounds = plan_text[plan_text.index('const SOUNDS'):plan_text.index('root.CastlePlan')]
    sound_roles = {}
    for role, ids in re.findall(r'(\w+): \[([\d, ]+)\]', sounds):
        for item in ids.split(', '):
            sound_roles[int(item)] = role
    papers = sorted({p for p in re.findall(r"'([AB]-PICT-\d+)'", shell)} |
                    {f"A-PICT-{p}" for p in re.findall(r'Data-A-PICT-(\d+)', shell)} |
                    {f"A-PICT-{p}" for p in re.findall(r'Data-A-PICT-(\d+)', folio)} |
                    {f"A-PICT-{p}" for p in re.findall(r"id: (\d{5}), title", folio)})
    out = ['# Asset and feature parity', '',
           'Generated by `archive/parity_ledger.py`. "In play" means a player meets it while playing, with no tool or cabinet.', '',
           '## Enchanted Scepters disk', '',
           '| Resource | Count | Where it lives |', '| --- | ---: | --- |',
           f"| ASCN rooms | {es_types['ASCN']} | All reachable on the original engine. Open rooms now have physical edges. |",
           f"| ATXT room text | {es_types['ATXT']} | Shown by the engine, verbatim, and kept in the Chronicle. |",
           f"| ACOD room scripts and GCOD | {es_types['ACOD'] + es_types['GCOD']} | Run unchanged by the engine. Their words are reachable by typing, or by the Try button. |",
           f"| ACHR characters | {es_types['ACHR']} | All on the engine, with portraits and lines in the Cast tab. Defeats are staged from each dying line. |",
           f"| AOBJ objects | {es_types['AOBJ']} | All on the engine. One, `nest.dk`, is in storage with no script and is shown in Scepters notes. |",
           f"| ASND sounds | {es_types['ASND']} | All referenced by the disk's scripts or characters. |",
           '', '### Text', '', '| Kind | Lines kept verbatim |', '| --- | ---: |']
    names = {'room': 'Room descriptions', 'edge': 'Blocked directions', 'event': 'Script events', 'speech': 'Dialogue', 'voice': 'Battle lines',
             'thing': 'Object messages', 'shell': 'Application text', 'castle': 'Dark Castle application text'}
    out += [f'| {names[k]} | {kinds[k]} |' for k in names]
    out += [f"| Total | {len(chronicle['lines'])} |", '',
            'One line needs a pirated copy: "The pirate laughs: Har, Har, Har!" sits behind the disk\'s BADCOPY# test. The engine reports a good copy, so it appears in the Chronicle only.', '',
            '## Dark Castle disk', '',
            '| Resource | Count | Where it lives |', '| --- | ---: | --- |',
            f'| PPCT sprite reels | {len(reels)} | All in The Enchanted Castle, listed below. |',
            f'| PSCR screens | {len(screens)} | 14 rooms, 3 foreground masks, 2 title screens, the Scores of Merit. |',
            f'| SOUN recordings | {len(sound_roles)} | All in The Enchanted Castle, listed below. The 73rd record is an empty header. |',
            f'| PICT pictures | {len(papers)} | Used in the game\'s screens or the Archive. |',
            '| ICON and ICN# art | 18 | Keycaps, save icons and the sad castle in the game, the castle mark on its title bar, the sad Macintosh on a load failure, the barred Macintosh XL in Oddities. |',
            f"| Rooms in CODE 5 | 14 | Floors, stairs, ladders, ropes, exits, entries and moving platforms decoded, not redrawn. |",
            f"| GPTH paths | {dc_types[('Data A', 'GPTH')]} | The Great Hall door runs. |",
            '| Jump tables in CODE 2 | 3 | Duncan\'s running, standing and downward jumps, row for row. Walk, ladder and fall rates come from the same code. The update rate is not proven, so game speed is judged. |',
            f"| SFTR tables | {dc_types[('Data A', 'SFTR')] + dc_types[('Data B', 'SFTR')]} | Decoded into `archive/dc/castle-data.js`. |",
            f"| Stbl score tables | {dc_types[('Data A', 'Stbl')]} | Decoded. Points in play follow the scoring card, PICT 20005. |",
            '| HISC, KDEF, DCAS | 3 | Opening high scores, key setup and the demo version note. |',
            '| DEMO recording | 1 | The Demo button replays its 1,053 bytes of recorded input in the rebuilt game. Creatures differ, so the run plays out differently. |',
            '| FONT strikes | 3 | Score Font on the status bar, DC Dialog Font on the Scores of Merit and door labels, the Scepters font for the adventure\'s own lines. |',
            '| CODE | 10 | Read for data only. No 1986 logic is executed. `archive/dc/rooms/` holds an independent partial trace, where unresolved facts stay null. |',
            '| System, Finder | - | Apple\'s files. Preserved in the Disk Cabinet, outside the game. |',
            '', '### Reels by role', '']
    grouped = {}
    for reel in reels:
        grouped.setdefault(roles.get(reel, 'UNPLACED'), []).append(reel)
    out += ['| Role | Reels |', '| --- | --- |'] + [f"| {role} | {' '.join(sorted(items))} |" for role, items in sorted(grouped.items())]
    out += ['', '### Recordings by role', '', '| Role | SOUN |', '| --- | --- |']
    grouped = {}
    for sound, role in sound_roles.items():
        grouped.setdefault(role, []).append(sound)
    out += [f"| {role} | {' '.join(map(str, sorted(items)))} |" for role, items in sorted(grouped.items())]
    out += ['', '### Pictures', '', ' '.join(papers), '',
            '## Feature parity', '',
            '| Original feature | This edition |', '| --- | --- |',
            '| Commands menu | Buttons from the disk\'s own MENU, every picture mode. |',
            '| Weapons menu and aim | Weapon buttons and Aim head, chest, side. |',
            '| WEAR | A Wear button on armor in the Pack, and typed. |',
            '| OFFER and ACCEPT | An Offer button in the Pack during a fight, and Accept when an enemy offers. |',
            '| Typed verbs | The command line, plus a Try button for keyboard-free play. Riddle and password answers are held back. |',
            '| Save, Revert | Save, Restore, doorway checkpoints. |',
            '| About box | VERS credits in the Archive. |',
            '| Dark Castle keys | W S A D, Space, Q, E, Tab, mouse aim and click, plus arrows, F, gamepad and touch buttons. Each input keeps one job, and the title and pause screens show one controls card. Modern controls are the default. Classic 1986 controls in Options restore fixed jumps, the one-axis mouse arm, throwing only when standing, and Q to pick things up. |',
            "| Duncan's arm | The mouse sets the arm, and the rock's speed, drop and bounds follow CODE 2. Holding the button repeats on the disk's six updates. Modern aim points the same arm at the pointer. |",
            "| Joining ladders | Span kinds 38 and 39, which carry Duncan between rooms with no key held. They decide how the Shield room is entered. |",
            '| Difficulty levels | Beginner, Intermediate, Advanced, with the disk\'s bonus and extra-man values. |',
            '| Scores of Merit | Opens with the disk\'s shipped scores. |',
            '| December 25 tree | In the Archive and in play. |', '']
    (ROOT / 'archive/PARITY.md').write_text('\n'.join(out), encoding='utf8')
    print(len(reels), len(screens), len(sound_roles), len(papers), 'unplaced', grouped.get('UNPLACED'))


if __name__ == '__main__':
    main()
