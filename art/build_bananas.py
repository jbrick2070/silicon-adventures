"""Banana-morphed weapon sprites for the refreshed layer.

Every weapon the player can swing, throw or fire keeps its native frame size,
anchor and behaviour; only its look changes while the refreshed layers are on.
The morph is strict 1-bit: the original ink and paper pixels are bent along a
crescent (nearest neighbour, no new tones), a ridge line runs along the upper
curve, a stem nub closes one end and a few ripening spots sit on the flesh.
The original plates in archive/es/plates/ are never touched; the L toggle
shows them again.  Output: art/refresh/sprites/banana/AOBJ-<id>.png and
art/refresh/banana-index.js (sprite path -> banana path)."""
from pathlib import Path
import json
from PIL import Image

ART = Path(__file__).resolve().parent
ROOT = ART.parent
OUT = ART / "refresh/sprites/banana"

WEAPONS = {"sword", "long sword", "scimitar", "axe", "dagger", "spear", "club", "scyth", "trident",
           "crossbow", "blowgun", "pistol", "blaster", "machine gun", "spear gun", "grenade", "bomb"}


def designs():
    js = (ROOT / "archive/es/designs.js").read_text(encoding="utf-8")
    return json.loads(js[js.index("[") : js.rindex("]") + 1])


def morph(src):
    im = Image.open(src).convert("RGBA")
    w, h = im.size
    px = im.load()
    bbox = im.getbbox()
    if not bbox:
        return im
    x0, y0, x1, y1 = bbox
    bw, bh = x1 - x0, y1 - y0
    # Crescent bend: the ends rise and the middle sags, the way a banana rests,
    # by two fifths of the sprite's height. The drawing is first squeezed
    # vertically (nearest neighbour, never below 70%) so the bend fits inside
    # the native frame; the frame itself never changes.
    amp = bh * 0.4
    squeeze = max(0.7, (h - amp) / max(1, bh)) if bh + amp > h else 1.0
    out = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    o = out.load()
    mid = (y0 + y1) / 2
    for x in range(w):
        u = (2 * (x - x0) / max(1, bw)) - 1 if x0 <= x < x1 else 1
        dy = amp * (0.5 - u * u)
        for y in range(h):
            sy = mid + (y - dy - mid) / squeeze
            syi = int(round(sy))
            if 0 <= syi < h and px[x, syi][3] >= 128:
                r = px[x, syi][0]
                o[x, y] = (0, 0, 0, 255) if r < 128 else (255, 255, 255, 255)
    # Ridge along the lower third of the curve, stem nub at the thicker end, and ripening spots.
    spans = {}
    for x in range(w):
        ys = [y for y in range(h) if o[x, y][3] >= 128]
        if ys:
            spans[x] = (ys[0], ys[-1])
    xs = sorted(spans)
    if not xs:
        return out
    for x in xs[4:-4]:
        top, bot = spans[x]
        yr = top + max(1, (bot - top) * 0.68)
        y = int(yr)
        if 0 <= y < h and o[x, y][0] == 255:
            o[x, y] = (0, 0, 0, 255)
    thick_left = sum(spans[x][1] - spans[x][0] for x in xs[: len(xs) // 4])
    thick_right = sum(spans[x][1] - spans[x][0] for x in xs[-len(xs) // 4 :])
    stem_x = xs[0] if thick_left >= thick_right else xs[-1]
    top, bot = spans[stem_x]
    cy = (top + bot) // 2
    for dx in range(-2, 3):
        for dy in range(-1, 2):
            x, y = stem_x + dx, cy + dy
            if 0 <= x < w and 0 <= y < h:
                o[x, y] = (0, 0, 0, 255)
    for k in range(3):
        x = xs[int(len(xs) * (0.3 + 0.2 * k))]
        top, bot = spans[x]
        y = top + int((bot - top) * 0.3)
        for dx in range(2):
            for dy in range(2):
                if x + dx < w and y + dy < h and o[x + dx, y + dy][0] == 255:
                    o[x + dx, y + dy] = (0, 0, 0, 255)
    return out


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    index = {}
    for d in designs():
        if d["type"] != "AOBJ" or d["name"] not in WEAPONS:
            continue
        im = morph(ROOT / d["path"])
        dest = OUT / f"AOBJ-{d['id']}.png"
        im.save(dest, optimize=True)
        index[d["path"]] = dest.relative_to(ROOT).as_posix()
    js = ("/* Generated by art/build_bananas.py. Refreshed-layer stand-ins for the weapon sprites:\n"
          " * the same native frames, bent into bananas. Originals stay in archive/es/plates/. */\n"
          f"window.RefreshBananas = {json.dumps(index, indent=2)};\n")
    (ART / "refresh/banana-index.js").write_text(js, encoding="utf-8")
    print(f"Built {len(index)} banana weapons.")


if __name__ == "__main__":
    main()
